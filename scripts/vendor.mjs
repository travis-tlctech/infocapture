// Rebuilds app/vendor/* from the pinned devDependencies:
//   npm install && npm run vendor
// The app has no build step; these two files are the only bundled code.
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'app', 'vendor');
mkdirSync(out, { recursive: true });
const version = (pkg) => JSON.parse(readFileSync(join(root, 'node_modules', pkg, 'package.json'), 'utf8')).version;

await build({
  bundle: true,
  format: 'esm',
  minify: true,
  target: 'es2020',
  legalComments: 'none',
  absWorkingDir: root,
  logLevel: 'warning',
  stdin: { contents: "export { createClient } from '@supabase/supabase-js';", resolveDir: root },
  banner: { js: `/*! @supabase/supabase-js ${version('@supabase/supabase-js')} | MIT | https://github.com/supabase/supabase-js */` },
  outfile: join(out, 'supabase.min.js'),
});
// jsQR ships as UMD; minify it as-is so it sets window.jsQR.
await build({
  entryPoints: [join(root, 'node_modules', 'jsqr', 'dist', 'jsQR.js')],
  minify: true,
  legalComments: 'none',
  logLevel: 'warning',
  banner: { js: `/*! jsQR ${version('jsqr')} | Apache-2.0 | https://github.com/cozmo/jsQR */` },
  outfile: join(out, 'jsQR.min.js'),
});
writeFileSync(join(out, 'README.md'), `Generated by \`npm run vendor\` from the versions pinned in package.json. Do not edit by hand.\n\n- @supabase/supabase-js ${version('@supabase/supabase-js')} (MIT)\n- jsqr ${version('jsqr')} (Apache-2.0)\n`);
console.log('vendor files written to app/vendor');
