// Rebuilds app/vendor/* from the pinned devDependencies:
//   npm install && npm run vendor
// The app has no build step; these three files are the only bundled code.
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'app', 'vendor');
mkdirSync(out, { recursive: true });
const version = (pkg) => JSON.parse(readFileSync(join(root, 'node_modules', pkg, 'package.json'), 'utf8')).version;

const msalBanner = `/*! @azure/msal-browser ${version('@azure/msal-browser')} | MIT | https://github.com/AzureAD/microsoft-authentication-library-for-js */`;
const common = { bundle: true, format: 'esm', minify: true, target: 'es2020', legalComments: 'none', absWorkingDir: root, logLevel: 'warning' };

await build({
  ...common,
  stdin: { contents: "export { PublicClientApplication, InteractionRequiredAuthError, BrowserAuthError } from '@azure/msal-browser';", resolveDir: root },
  banner: { js: msalBanner },
  outfile: join(out, 'msal-browser.min.js'),
});
await build({
  ...common,
  stdin: { contents: "export { broadcastResponseToMainFrame } from '@azure/msal-browser/redirect-bridge';", resolveDir: root },
  banner: { js: msalBanner },
  outfile: join(out, 'msal-redirect-bridge.min.js'),
});
// jsQR ships as UMD; minify it as-is so it sets window.jsQR.
await build({
  entryPoints: [join(root, 'node_modules', 'jsqr', 'dist', 'jsQR.js')],
  minify: true,
  legalComments: 'none',
  logLevel: 'warning',
  banner: { js: `/*! jsQR ${version('jsqr')} | Apache-2.0 | https://github.com/cozmo/jsQR */` },
  outfile: join(out, 'jsQR.min.js'),
});
writeFileSync(join(out, 'README.md'), `Generated by \`npm run vendor\` from the versions pinned in package.json. Do not edit by hand.\n\n- @azure/msal-browser ${version('@azure/msal-browser')} (MIT)\n- jsqr ${version('jsqr')} (Apache-2.0)\n`);
console.log('vendor files written to app/vendor');
