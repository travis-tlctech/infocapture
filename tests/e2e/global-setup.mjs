// Builds test fixtures: a badge image with a vCard QR code (also as a Y4M
// "camera feed" for Chromium's fake webcam), a QR with delimited text, and a
// business card photo. Needs ffmpeg on PATH.
import { chromium } from '@playwright/test';
import QRCode from 'qrcode';
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

export const FIXTURES = join(dirname(fileURLToPath(import.meta.url)), '..', '.fixtures');

export const BADGE_VCARD = [
  'BEGIN:VCARD',
  'VERSION:3.0',
  'N:Okafor;Jordan;;;',
  'FN:Jordan Okafor',
  'ORG:Northwind Traders',
  'TITLE:Director of Learning',
  'EMAIL:jordan.okafor@northwind.example',
  'TEL;TYPE=CELL:+1 312 555 0147',
  'END:VCARD',
].join('\r\n');

export const DELIMITED_QR = 'Wei^Chen^Fabrikam Inc^Operations Lead^wei.chen@fabrikam.example';

export default async function globalSetup() {
  mkdirSync(join(FIXTURES, 'screens'), { recursive: true });
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });

  const badge = async (text, file) => {
    const qr = await QRCode.toDataURL(text, { margin: 2, width: 300, errorCorrectionLevel: 'M' });
    await page.setContent(`<body style="margin:0;background:#3b4752;display:grid;place-items:center;height:720px;font-family:sans-serif">
      <div style="background:#fff;width:440px;height:640px;border-radius:18px;display:grid;justify-items:center;align-content:center;gap:12px">
        <div style="font-size:34px;font-weight:700">EXPO 2026</div><img src="${qr}" width="300" height="300"><div style="font-size:28px">ATTENDEE</div>
      </div></body>`);
    await page.screenshot({ path: file });
  };
  const badgePng = join(FIXTURES, 'badge-vcard.png');
  await badge(BADGE_VCARD, badgePng);
  await badge(DELIMITED_QR, join(FIXTURES, 'badge-delimited.png'));

  await page.setViewportSize({ width: 1000, height: 600 });
  await page.setContent(`<body style="margin:0;background:#c9c2b5;display:grid;place-items:center;height:600px;font-family:Georgia,serif">
    <div style="background:#fbfaf6;width:840px;height:480px;box-shadow:0 8px 30px #0005;padding:48px;box-sizing:border-box;position:relative">
      <div style="font-size:46px;font-weight:700;color:#123">Priya Raman</div>
      <div style="font-size:26px;color:#555;margin-top:6px">VP, People Operations</div>
      <div style="position:absolute;bottom:48px;left:48px;font:22px/1.6 sans-serif;color:#222">Contoso Health<br>priya.raman@contoso-health.example<br>m +1 646 555 0188 · o +1 646 555 0100</div>
    </div></body>`);
  await page.screenshot({ path: join(FIXTURES, 'card.png') });
  await browser.close();

  const feed = join(FIXTURES, 'badge-vcard.y4m');
  execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-loop', '1', '-i', badgePng, '-t', '1', '-r', '5', '-pix_fmt', 'yuv420p', feed]);
  if (!existsSync(feed)) throw new Error('ffmpeg did not produce the fake camera feed');
  writeFileSync(join(FIXTURES, 'README.txt'), 'Generated by tests/e2e/global-setup.mjs. Safe to delete.\n');
}
